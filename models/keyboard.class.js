/**
 * Tracks the keyboard input state used to control the player character.
 * @class Keyboard
 */
class Keyboard {
  /** Indicates whether the left movement key is currently pressed. */
  LEFT = false;

  /** Indicates whether the right movement key is currently pressed. */
  RIGHT = false;

  /** Indicates whether the jump key is currently pressed. */
  SPACE = false;

  /** Indicates whether the throw bottle key is currently pressed. */
  D = false;
}
